/**
 * 3D 世界の寸法・見た目に関わる定数。
 * 1 単位 = 1m として扱う。
 */

/**
 * コース 1 周の長さ（m）。すべての配置はコース座標 s ∈ [0, COURSE_LENGTH) で定義する。
 * 描画はカメラから ±COURSE_LENGTH / 2（±50m）で折り返すため、地面や配置物の可視範囲はこれより内側に収めること
 */
export const COURSE_LENGTH = 100

/**
 * 見た目の惑星半径（m）。コース長とは独立した値で、湾曲の強さだけを決める。
 * Phase 1 で候補を見比べ、デフォルメの効いた小惑星らしさを優先して 63.7m に決めた。
 * この半径では地平線が約 14.5m 先、高さ 8m の木が見え始めるのは約 46m 先になる
 */
export const PLANET_RADIUS = 63.7

/** デバッグ GUI で切り替えて見比べる惑星半径の候補（m） */
export const PLANET_RADIUS_CANDIDATES = [63.7, 150, 300] as const

/** 目の高さ（m） */
export const EYE_HEIGHT = 1.65

/** 道の半幅（m）。道幅は 2 倍の 2.4m */
export const PATH_HALF_WIDTH = 1.2

/** 霧と背景の色。空の地平線付近の色と一致させ、地面の端やオブジェクトの出現を霧に溶かす */
export const FOG_COLOR = "#6f8f88"

/**
 * 霧が掛かり始める距離（m、カメラからの直線距離。曲げ変換を使うマテリアルは直線距離で霧を掛ける）。
 * 目の前からごく薄く掛け、森全体を霞ませる。地平線の向こうからせり上がる物は霧の中から現れる。
 * 2026-10-13 にユーザーがデバッグ GUI で選んだ値（Phase 2 の 8m から変更）
 */
export const FOG_NEAR = 1.5

/**
 * 霧で完全に見えなくなる距離（m、カメラからの直線距離）。
 * 描画はカメラから ±COURSE_LENGTH / 2（50m）で折り返し、物が 1 周の反対側へ切り替わる。
 * その手前で完全に霧へ溶かし、切り替わる瞬間と地面の端（最大 49m）を見せないようにする。
 * 霧に溶けきる距離が 45m 以下なら、前方 45〜50m で描画対象に入る配置物は現れた時点で見えない。
 * 2026-10-13 にユーザーがデバッグ GUI で選んだ値（Phase 2 の 45m から変更）。森の奥が早く霞み、見通しが短くなる
 */
export const FOG_FAR = 34

/**
 * 配置物のチャンクの長さ（m）。COURSE_LENGTH を割り切る値にする（100m なら 20 チャンク）。
 * カメラが別のチャンクへ入ったときだけ、描画する配置物を詰め直す。
 * チャンクが長いと、新しく詰めたチャンクが手前に現れて霧に溶けきらない（10m だと 40m 先、霧の掛かり方は約 94%）。
 * 5m にして、新しいチャンクが 45m 先（霧で完全に見えない位置）から入るようにした
 */
export const CHUNK_LENGTH = 5

/**
 * カメラのいるチャンクから前方・後方に何チャンク分を描画するか。
 * 前方 9 チャンクなら、カメラの位置によって 45〜50m 先までが描画対象になる。
 * 前方の端は 50m 未満にすること。50m を超えると、その物が 1 周の反対側（後方）へ折り返して描かれる。
 * 後方は振り向かないため、横に広がる木の枝が画面の端に残る分だけ 2 チャンク（10m）描く。
 * 合計（2 + 1 + 9 = 12 チャンク = 60m）は 1 周より短くし、同じ物が前後に二重に描かれないようにする
 */
export const VISIBLE_CHUNKS_AHEAD = 9
export const VISIBLE_CHUNKS_BEHIND = 2
