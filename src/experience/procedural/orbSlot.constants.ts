/**
 * オーブを置く位置の定数。距離は m で表す。
 */

/**
 * オーブの間隔（m）。COURSE_LENGTH を割り切る値にする（起動時に検証する）。
 * 2026-10-13 にユーザーの判断で 10m に決めた（1 周 100m に 10 個）。
 * 変えたときは、ORB_CONTENTS の件数を COURSE_LENGTH ÷ この値に合わせること
 */
export const ORB_SPACING = 10

/**
 * 道の中心からオーブまでの横距離（m）。左右交互に置く（0 番目は左）。
 * 道の真ん中に置くと、カメラ（道の中央を歩く）がオーブを突き抜けるため、道の上で少し脇へずらす
 */
export const ORB_SIDE_OFFSET = 0.8

/** 地面からオーブ（浮遊の中心）までの高さ（m）。目の高さ（1.65m）より少し下に浮かべる */
export const ORB_HEIGHT = 1.2

/**
 * オーブの周りで、木・岩を置かない半径（m）。配置物の clearance に足して判定する。
 * 道の縁の木（道の中心から 2m〜）がオーブのすぐ横に生えて、オーブを隠さないようにする
 */
export const ORB_CLEARANCE = 1
